LOCATOR_COMMENT_RE = re.compile(r"^<!--\s*LOCATOR:\s*(\{.*?\})\s*-->$")
AUTH_HEADING_RE = re.compile(r"^##\s+\[(AUTH:[^\]]+)\]\s+(.+)$", re.MULTILINE)
PDF_HEADING_RE = re.compile(
    r"^(?:CHAPTER|SECTION|ARTICLE|RULE|PART|SUBCHAPTER|TITLE|§+|\d+\.\d+)\b[^\n]{1,90}$",
    re.IGNORECASE,
)
CANONICAL_GENERATED_MARKER = "<!-- GENERATED BY CanonicalIngestor -->"
SUPPORTED_CANONICAL_EXTENSIONS = {".md", ".txt", ".pdf", ".docx", ".xlsx", ".xlsm", ".csv"}


def _sha256_short(data: bytes) -> str:
    """Returns a short prefixed SHA-256 digest for tamper-evident locator stamping."""
    return f"sha256:{hashlib.sha256(data).hexdigest()[:18]}"


def _normalize_for_match(text: Optional[str]) -> str:
    """Normalizes whitespace and case for deterministic citation substring verification."""
    if not text:
        return ""
    return re.sub(r"\s+", " ", text).strip().lower()


def _parse_auth_blocks_from_text(content: str, source_file: str) -> List[CanonicalAuthorityRef]:
    """Parses `[AUTH:...]` Markdown blocks into structured `CanonicalAuthorityRef` objects."""
    parsed: List[CanonicalAuthorityRef] = []
    current_id: Optional[str] = None
    current_title = ""
    current_url: Optional[str] = None
    quote_lines: List[str] = []

    def flush_current() -> None:
        if current_id is not None:
            verbatim = "\n".join(quote_lines).strip()
            parsed.append(
                CanonicalAuthorityRef(
                    auth_id=current_id,
                    title=current_title.strip() or current_id,
                    url=current_url,
                    verbatim_quote=verbatim or current_title.strip() or current_id,
                    source_file=source_file,
                )
            )

    for raw_line in content.splitlines():
        heading_match = AUTH_HEADING_RE.match(raw_line.strip())
        if heading_match:
            flush_current()
            current_id = heading_match.group(1).strip()
            current_title = heading_match.group(2).strip()
            current_url = None
            quote_lines = []
            continue

        if current_id is None:
            continue

        stripped = raw_line.strip()
        if stripped.startswith("- **Title:**"):
            current_title = stripped.split("**Title:**", 1)[1].strip()
        elif stripped.startswith("- **URL:**"):
            url_val = stripped.split("**URL:**", 1)[1].strip()
            current_url = None if url_val.lower() in ("none", "n/a", "") else url_val
        elif stripped.startswith(
            ("- **Verbatim Holding:**", "- **Verbatim Rule:**", "- **Verbatim Text:**")
        ):
            val = stripped.split(":**", 1)[1].strip()
            if val:
                quote_lines.append(val)
        elif stripped and not stripped.startswith("---") and not stripped.startswith(CANONICAL_GENERATED_MARKER):
            quote_lines.append(stripped[1:].strip() if stripped.startswith(">") else stripped)

    flush_current()
    return parsed


class CanonicalRouter:
    """Two-level router for standing canonical authorities `(b)` under `canonical/`."""

    def __init__(self, canonical_dir: Path) -> None:
        """Initializes the canonical router.

        Args:
            canonical_dir: Path to the directory containing `INDEX.md` and domain
                subdirectories with `[AUTH:...]` anchored Markdown files.
        """
        self.canonical_dir = canonical_dir

    def get_index_markdown(self) -> str:
        """Reads `canonical/INDEX.md` for direct injection into Stage 1 planning.

        Returns:
            Full contents of `INDEX.md`, or a fallback note if none exists yet.
        """
        index_path = self.canonical_dir / "INDEX.md"
        if not index_path.exists():
            return "# Canonical Index\nNo canonical INDEX.md found."
        return index_path.read_text(encoding="utf-8")

    def list_authorities(self) -> Dict[str, CanonicalAuthorityRef]:
        """Scans all Markdown files under `canonical/` for `[AUTH:...]` blocks.

        Returns:
            Dictionary mapping `auth_id` (e.g., `'AUTH:HERTZ-2010-NERVE-CENTER'`)
            to `CanonicalAuthorityRef`.
        """
        authorities: Dict[str, CanonicalAuthorityRef] = {}
        if not self.canonical_dir.exists():
            return authorities

        for md_path in sorted(self.canonical_dir.rglob("*.md")):
            rel_parts = md_path.relative_to(self.canonical_dir).parts
            if (
                md_path.name == "INDEX.md"
                or md_path.name.endswith(".toc.md")
                or "raw" in rel_parts
            ):
                continue
            rel_path = str(md_path.relative_to(self.canonical_dir))
            content = md_path.read_text(encoding="utf-8")
            for auth in _parse_auth_blocks_from_text(content, rel_path):
                authorities[auth.auth_id] = auth

        return authorities

    def get_authority(self, auth_id: str) -> Optional[CanonicalAuthorityRef]:
        """Retrieves a single canonical authority by its `[AUTH:...]` identifier.

        Args:
            auth_id: Authority ID with or without surrounding brackets.

        Returns:
            Matching `CanonicalAuthorityRef` or `None`.
        """
        normalized = auth_id.strip().strip("[]")
        authorities = self.list_authorities()
        if normalized in authorities:
            return authorities[normalized]
        if not normalized.startswith("AUTH:") and f"AUTH:{normalized}" in authorities:
            return authorities[f"AUTH:{normalized}"]
        return None

    def get_authorities_context(self, auth_ids: Optional[List[str]] = None) -> str:
        """Formats selected (or all) canonical authorities into a prompt-ready block."""
        authorities = self.list_authorities()
        selected = (
            [authorities[aid] for aid in auth_ids if aid in authorities]
            if auth_ids
            else list(authorities.values())
        )
        chunks = []
        for auth in selected:
            chunks.append(
                f"### [{auth.auth_id}] {auth.title}\n"
                f"- Source: {auth.source_file or 'canonical'}\n"
                f"- URL: {auth.url or 'N/A'}\n"
                f"- Verbatim Text: {auth.verbatim_quote}\n"
            )
        return "\n".join(chunks)

    def build_stage1_tools(self) -> List[ToolDefinition]:
        """Constructs deterministic hierarchical discovery tools over canonical corpus `(b)`.

        Allows Stage 1 and Stage 2 agents to inspect per-document TOCs, search
        authorities filtered by domain/document, and fetch exact verbatim `[AUTH:...]`
        entries without stuffing an entire corpus into the prompt context.
        """

        def _toc_path_for(doc_id: str) -> Optional[Path]:
            normalized = doc_id.strip().lstrip("/")
            candidates: List[Path] = []
            if normalized.endswith(".toc.md"):
                candidates.append(self.canonical_dir / normalized)
            elif normalized.endswith(".md"):
                base = normalized[:-3]
                candidates.append(self.canonical_dir / f"{base}.toc.md")
                if base.endswith(".authorities"):
                    candidates.append(self.canonical_dir / f"{base[:-12]}.toc.md")
            else:
                candidates.append(self.canonical_dir / f"{normalized}.toc.md")
            for cand in candidates:
                if cand.exists():
                    return cand
            return None

        def browse_canonical_toc(doc_id: str) -> Dict[str, Any]:
            toc_path = _toc_path_for(doc_id)
            if toc_path is not None:
                return {
                    "doc_id": doc_id,
                    "toc_file": str(toc_path.relative_to(self.canonical_dir)),
                    "content": toc_path.read_text(encoding="utf-8"),
                }

            normalized = doc_id.strip().lstrip("/").removesuffix(".md").removesuffix(".toc")
            matches = [
                {
                    "auth_id": a.auth_id,
                    "title": a.title,
                    "url": a.url,
                    "source_file": a.source_file,
                    "preview": a.verbatim_quote[:140],
                }
                for a in self.list_authorities().values()
                if a.source_file and normalized in a.source_file
            ]
            if not matches:
                return {"error": f"No canonical TOC or authorities found for doc_id='{doc_id}'."}
            return {"doc_id": doc_id, "entries": matches}

        def search_canonical_authorities(
            query: str,
            domain: Optional[str] = None,
            doc_id: Optional[str] = None,
            max_results: int = 10,
        ) -> Dict[str, Any]:
            q_lower = query.strip().lower()
            tokens = [t for t in re.findall(r"[a-z0-9§]+", q_lower) if len(t) >= 3]
            scored: List[Tuple[int, CanonicalAuthorityRef]] = []

            for auth in self.list_authorities().values():
                src = (auth.source_file or "").lower()
                if domain and not src.startswith(f"{domain.strip().lower()}/"):
                    continue
                if doc_id:
                    doc_slug = doc_id.strip().lower().removesuffix(".md").removesuffix(".toc")
                    if doc_slug not in src:
                        continue
                haystack = f"{auth.auth_id} {auth.title} {auth.verbatim_quote}".lower()
                score = 0
                if q_lower and q_lower in haystack:
                    score += 10
                score += sum(1 for tok in tokens if tok in haystack)
                if score > 0 or q_lower == "*":
                    scored.append((score, auth))

            scored.sort(key=lambda pair: (-pair[0], pair[1].auth_id))
            results = [
                {
                    "auth_id": a.auth_id,
                    "title": a.title,
                    "source_file": a.source_file,
                    "url": a.url,
                    "preview": a.verbatim_quote[:240],
                }
                for _, a in scored[:max_results]
            ]
            return {
                "query": query,
                "domain": domain,
                "doc_id": doc_id,
                "match_count": len(results),
                "matches": results,
            }

        def read_canonical_authority(auth_id: str) -> Dict[str, Any]:
            auth = self.get_authority(auth_id)
            if auth is None:
                return {"error": f"No canonical authority found with auth_id='{auth_id}'."}
            return auth.model_dump()

        return [
            ToolDefinition(
                name="browse_canonical_toc",
                description=(
                    "Read the Tier-2 Table of Contents (.toc.md) or authority listing for a "
                    "canonical document selected from canonical/INDEX.md."
                ),
                parameters_schema={
                    "type": "object",
                    "properties": {
                        "doc_id": {
                            "type": "string",
                            "description": "Document identifier or path from INDEX.md (e.g., 'legal/federal_jurisdiction').",
                        }
                    },
                    "required": ["doc_id"],
                },
                handler=browse_canonical_toc,
            ),
            ToolDefinition(
                name="search_canonical_authorities",
                description=(
                    "Search canonical [AUTH:...] rules by keyword, statutory section, or topic, "
                    "optionally scoped to a domain or doc_id."
                ),
                parameters_schema={
                    "type": "object",
                    "properties": {
                        "query": {
                            "type": "string",
                            "description": "Search keywords (e.g., '1332 nerve center' or '547 preference').",
                        },
                        "domain": {
                            "type": "string",
                            "description": "Optional domain folder filter (e.g., 'legal', 'talent').",
                        },
                        "doc_id": {
                            "type": "string",
                            "description": "Optional document path filter from INDEX.md.",
                        },
                        "max_results": {
                            "type": "integer",
                            "description": "Maximum results to return (default 10).",
                        },
                    },
                    "required": ["query"],
                },
                handler=search_canonical_authorities,
            ),
            ToolDefinition(
                name="read_canonical_authority",
                description=(
                    "Fetch the full verbatim rule/holding text and URL for a specific [AUTH:...] ID."
                ),
                parameters_schema={
                    "type": "object",
                    "properties": {
                        "auth_id": {
                            "type": "string",
                            "description": "Exact canonical authority ID (e.g., 'AUTH:28-USC-1332-A').",
                        }
                    },
                    "required": ["auth_id"],
                },
                handler=read_canonical_authority,
            ),
        ]


class CanonicalIngestor:
    """Deterministic raw-to-anchored ingestor for the canonical knowledge corpus `(b)`.

    Converts raw authoritative files (`.md`, `.txt`, `.pdf`, `.docx`, `.xlsx`, `.xlsm`,
    `.csv`) placed under `canonical/raw/<domain>/` — or un-anchored raw files placed
    directly under `canonical/<domain>/` — into `[AUTH:...]` anchored Markdown files
    and rebuilds `canonical/INDEX.md` for Stage 1 routing.
    """

    def __init__(self, canonical_dir: Path) -> None:
        """Initializes the canonical corpus ingestor.

        Args:
            canonical_dir: Root directory storing `INDEX.md`, `raw/<domain>/`, and
                encoded domain `.md` files.
        """
        self.canonical_dir = canonical_dir
        self.raw_dir = canonical_dir / "raw"

    @staticmethod
    def _slugify(value: str, fallback: str = "general") -> str:
        """Normalizes a filename, domain, or identifier segment into lowercase snake_case."""
        cleaned = re.sub(r"[^a-zA-Z0-9_-]+", "_", value.strip()).strip("_").lower()
        return cleaned or fallback

    @staticmethod
    def _mint_auth_id(domain: str, stem: str, index: int, suffix: str = "") -> str:
        """Creates a deterministic uppercase `[AUTH:...]` identifier."""
        dom_part = re.sub(r"[^A-Z0-9]+", "-", domain.upper()).strip("-") or "CANON"
        stem_part = re.sub(r"[^A-Z0-9]+", "-", stem.upper()).strip("-") or "DOC"
        if len(stem_part) > 18:
            stem_part = stem_part[:18].rstrip("-")
        mid = f"{suffix}-" if suffix else ""
        return f"AUTH:{dom_part}-{stem_part}-{mid}{index:03d}"

    def create_domain(self, domain: str) -> Path:
        """Ensures `canonical/raw/<domain>/` exists and returns its path."""
        dom_slug = self._slugify(domain, fallback="general")
        target = self.raw_dir / dom_slug
        target.mkdir(parents=True, exist_ok=True)
        return target

    @staticmethod
    def _extract_docx_paragraphs(raw_path: Path) -> List[Tuple[bool, str]]:
        """Extracts `(is_heading, text)` paragraphs from a `.docx` file using stdlib XML."""
        paragraphs: List[Tuple[bool, str]] = []
        w_ns = "{http://schemas.openxmlformats.org/wordprocessingml/2006/main}"
        with zipfile.ZipFile(raw_path, "r") as zf:
            if "word/document.xml" not in zf.namelist():
                return paragraphs
            xml_bytes = zf.read("word/document.xml")

        root = ET.fromstring(xml_bytes)
        for p_elem in root.iter(f"{w_ns}p"):
            style_elem = p_elem.find(f".//{w_ns}pStyle")
            style_val = style_elem.get(f"{w_ns}val", "") if style_elem is not None else ""
            is_heading = style_val.lower().startswith("heading") or style_val.lower() == "title"
            texts = [t.text for t in p_elem.iter(f"{w_ns}t") if t.text]
            joined = "".join(texts).strip()
            if joined:
                paragraphs.append((is_heading, joined))
        return paragraphs

    def _chunk_markdown_or_text(
        self, raw_path: Path, domain: str, rel_source: str
    ) -> List[Dict[str, Optional[str]]]:
        """Chunks a `.md` or `.txt` document into discrete `[AUTH:...]` rule records."""
        content = raw_path.read_text(encoding="utf-8")
        # Preserve files that already contain authored [AUTH:...] blocks verbatim
        if AUTH_HEADING_RE.search(content):
            return [
                {
                    "auth_id": auth.auth_id,
                    "title": auth.title,
                    "url": auth.url,
                    "verbatim_rule": auth.verbatim_quote,
                }
                for auth in _parse_auth_blocks_from_text(content, rel_source)
            ]

        lines = content.splitlines()
        heading_re = re.compile(r"^(#{1,3})\s+(.+)$")
        sections: List[Tuple[str, int, int, List[str]]] = []
        curr_heading: Optional[str] = None
        curr_start = 1
        curr_body: List[str] = []

        for idx, line in enumerate(lines, start=1):
            hm = heading_re.match(line.strip())
            if hm:
                if curr_heading is not None and "\n".join(curr_body).strip():
                    sections.append((curr_heading, curr_start, idx - 1, curr_body))
                curr_heading = hm.group(2).strip()
                curr_start = idx
                curr_body = []
            else:
                if curr_heading is None and line.strip():
                    curr_heading = f"{raw_path.stem} (Rule Block)"
                    curr_start = idx
                if curr_heading is not None:
                    curr_body.append(line)
        if curr_heading is not None and "\n".join(curr_body).strip():
            sections.append((curr_heading, curr_start, len(lines), curr_body))

        # If a single section or no headings exist, split into paragraph blocks
        entries: List[Dict[str, Optional[str]]] = []
        if len(sections) <= 1 and len(lines) > 1:
            paragraphs: List[Tuple[int, int, str]] = []
            buf: List[str] = []
            p_start = 1
            for idx, line in enumerate(lines, start=1):
                stripped = line.strip()
                if heading_re.match(stripped):
                    if buf:
                        paragraphs.append((p_start, idx - 1, " ".join(buf).strip()))
                        buf = []
                    continue
                if not stripped:
                    if buf:
                        paragraphs.append((p_start, idx - 1, " ".join(buf).strip()))
                        buf = []
                else:
                    if not buf:
                        p_start = idx
                    buf.append(stripped)
            if buf:
                paragraphs.append((p_start, len(lines), " ".join(buf).strip()))

            for seq, (s_ln, e_ln, text) in enumerate(paragraphs, start=1):
                if not text:
                    continue
                short_title = text.split(".", 1)[0][:72].strip() or f"{raw_path.stem} Rule {seq}"
                entries.append(
                    {
                        "auth_id": self._mint_auth_id(domain, raw_path.stem, seq),
                        "title": short_title,
                        "url": f"file://{rel_source}#L{s_ln}-L{e_ln}",
                        "verbatim_rule": text,
                    }
                )
            return entries

        for seq, (heading, s_ln, e_ln, body_lines) in enumerate(sections, start=1):
            body_text = "\n".join(ln.strip() for ln in body_lines if ln.strip()).strip()
            if not body_text:
                continue
            entries.append(
                {
                    "auth_id": self._mint_auth_id(domain, raw_path.stem, seq),
                    "title": heading,
                    "url": f"file://{rel_source}#L{s_ln}-L{e_ln}",
                    "verbatim_rule": body_text,
                }
            )
        return entries

    def _chunk_pdf(
        self, raw_path: Path, domain: str, rel_source: str
    ) -> List[Dict[str, Optional[str]]]:
        """Extracts heading-aware page/section blocks from a canonical PDF via `pdfplumber`."""
        entries: List[Dict[str, Optional[str]]] = []
        seq = 0
        curr_heading = f"{raw_path.stem} Section"
        with pdfplumber.open(raw_path) as pdf:
            for page_idx, page in enumerate(pdf.pages, start=1):
                raw_text = (page.extract_text() or "").strip()
                if not raw_text:
                    continue
                paras = [p.strip() for p in re.split(r"\n\s*\n", raw_text) if p.strip()]
                buffer_paras: List[str] = []

                def flush_pdf_buffer() -> None:
                    nonlocal seq
                    if not buffer_paras:
                        return
                    combined = re.sub(r"\s+", " ", " ".join(buffer_paras)).strip()
                    buffer_paras.clear()
                    if not combined:
                        return
                    seq += 1
                    first_sentence = re.split(r"(?<![A-Z])\.\s+", combined, maxsplit=1)[0][:80].strip()
                    title = (
                        curr_heading
                        if curr_heading != f"{raw_path.stem} Section"
                        else (first_sentence or f"{raw_path.stem} p.{page_idx}")
                    )
                    entries.append(
                        {
                            "auth_id": self._mint_auth_id(domain, raw_path.stem, seq, suffix=f"P{page_idx}"),
                            "title": title[:100],
                            "url": f"file://{rel_source}#page={page_idx}",
                            "verbatim_rule": combined,
                        }
                    )

                for para in paras:
                    first_line = para.splitlines()[0].strip() if para.splitlines() else ""
                    if PDF_HEADING_RE.match(first_line) and len(para.splitlines()) == 1:
                        flush_pdf_buffer()
                        curr_heading = first_line[:100]
                        continue
                    if PDF_HEADING_RE.match(first_line) and len(para.splitlines()) > 1:
                        flush_pdf_buffer()
                        curr_heading = first_line[:100]
                        remainder = "\n".join(para.splitlines()[1:]).strip()
                        if remainder:
                            buffer_paras.append(remainder)
                        continue
                    if sum(len(x) for x in buffer_paras) + len(para) > 1800 and buffer_paras:
                        flush_pdf_buffer()
                    buffer_paras.append(para)

                flush_pdf_buffer()
        return entries

    def _chunk_docx(
        self, raw_path: Path, domain: str, rel_source: str
    ) -> List[Dict[str, Optional[str]]]:
        """Extracts heading-grouped rule blocks from a canonical `.docx` document."""
        paragraphs = self._extract_docx_paragraphs(raw_path)
        entries: List[Dict[str, Optional[str]]] = []
        curr_heading = f"{raw_path.stem} Rule"
        seq = 0

        for idx, (is_heading, text) in enumerate(paragraphs, start=1):
            if is_heading:
                curr_heading = text
                continue
            seq += 1
            entries.append(
                {
                    "auth_id": self._mint_auth_id(domain, raw_path.stem, seq),
                    "title": curr_heading if len(paragraphs) > 1 else text[:72],
                    "url": f"file://{rel_source}#para={idx}",
                    "verbatim_rule": text,
                }
            )
        return entries

    def _chunk_spreadsheet(
        self, raw_path: Path, domain: str, rel_source: str
    ) -> List[Dict[str, Optional[str]]]:
        """Converts `.xlsx`, `.xlsm`, or `.csv` rubric/policy tables into `[AUTH:...]` rows."""
        entries: List[Dict[str, Optional[str]]] = []
        rows_by_sheet: List[Tuple[str, List[List[str]]]] = []

        if raw_path.suffix.lower() == ".csv":
            with raw_path.open("r", encoding="utf-8", newline="") as f:
                rows_by_sheet.append(
                    ("CSV", [[str(c).strip() for c in row] for row in csv.reader(f)])
                )
        else:
            wb = openpyxl.load_workbook(raw_path, data_only=True)
            for sname in wb.sheetnames:
                ws = wb[sname]
                sheet_rows: List[List[str]] = []
                for row in ws.iter_rows(values_only=True):
                    sheet_rows.append(["" if v is None else str(v).strip() for v in row])
                rows_by_sheet.append((sname, sheet_rows))

        seq = 0
        for sheet_name, rows in rows_by_sheet:
            non_empty = [r for r in rows if any(cell for cell in r)]
            if not non_empty:
                continue
            headers = non_empty[0]
            data_rows = non_empty[1:] if len(non_empty) > 1 else non_empty
            for row_offset, row in enumerate(data_rows, start=2 if len(non_empty) > 1 else 1):
                pairs = [
                    f"{headers[i] if i < len(headers) and headers[i] else f'Col{i + 1}'}: {val}"
                    for i, val in enumerate(row)
                    if val
                ]
                if not pairs:
                    continue
                seq += 1
                row_title = row[0] if row[0] else f"{raw_path.stem} {sheet_name} Row {row_offset}"
                entries.append(
                    {
                        "auth_id": self._mint_auth_id(domain, raw_path.stem, seq, suffix=f"R{row_offset}"),
                        "title": row_title[:90],
                        "url": f"file://{rel_source}#sheet={sheet_name}&row={row_offset}",
                        "verbatim_rule": " | ".join(pairs),
                    }
                )
        return entries

    def _toc_path_for_source(self, source_file: str) -> Path:
        """Computes the Tier 2 `.toc.md` path corresponding to an encoded `source_file`."""
        rel = Path(source_file)
        stem = rel.stem
        if stem.endswith(".authorities"):
            stem = stem[:-12]
        return self.canonical_dir / rel.parent / f"{stem}.toc.md"

    def _write_toc_file(
        self, source_file: str, domain: str, auth_list: List[CanonicalAuthorityRef]
    ) -> Path:
        """Writes Tier 2 per-document Table of Contents (`<domain>/<slug>.toc.md`)."""
        toc_path = self._toc_path_for_source(source_file)
        toc_path.parent.mkdir(parents=True, exist_ok=True)
        lines: List[str] = [
            CANONICAL_GENERATED_MARKER,
            f"# Table of Contents — `{source_file}`",
            "",
            f"- **Domain:** `{domain}`",
            f"- **Total Authorities:** {len(auth_list)}",
            "",
            "| Authority ID | Heading / Section | Reference | 1-Line Preview |",
            "| :--- | :--- | :--- | :--- |",
        ]
        for auth in auth_list:
            snippet = auth.verbatim_quote.replace("\n", " ").replace("|", "/").strip()
            if len(snippet) > 120:
                snippet = snippet[:117].rstrip() + "..."
            safe_title = auth.title.replace("|", "/").strip()
            ref_url = (auth.url or "None").replace("|", "/")
            lines.append(f"| `[{auth.auth_id}]` | {safe_title} | {ref_url} | {snippet} |")
        lines.append("")
        toc_path.write_text("\n".join(lines), encoding="utf-8")
        return toc_path

    def _encode_single_file(self, raw_path: Path, domain: str, rel_source: str) -> Tuple[Path, int]:
        """Parses one raw canonical source file and writes Tier 3 `[AUTH:...]` + Tier 2 `.toc.md`."""
        suffix = raw_path.suffix.lower()
        if suffix in (".md", ".txt"):
            records = self._chunk_markdown_or_text(raw_path, domain, rel_source)
        elif suffix == ".pdf":
            records = self._chunk_pdf(raw_path, domain, rel_source)
        elif suffix == ".docx":
            records = self._chunk_docx(raw_path, domain, rel_source)
        elif suffix in (".xlsx", ".xlsm", ".csv"):
            records = self._chunk_spreadsheet(raw_path, domain, rel_source)
        else:
            return raw_path, 0

        domain_dir = self.canonical_dir / domain
        domain_dir.mkdir(parents=True, exist_ok=True)
        out_slug = self._slugify(raw_path.stem, fallback="authority")
        # If reading an un-anchored .md directly inside canonical/<domain>/ (outside raw/),
        # emit <stem>.authorities.md so we never clobber the user's raw source file.
        if raw_path.parent == domain_dir and suffix == ".md":
            out_path = domain_dir / f"{out_slug}.authorities.md"
        else:
            out_path = domain_dir / f"{out_slug}.md"

        lines: List[str] = [
            CANONICAL_GENERATED_MARKER,
            f"# {domain.replace('_', ' ').title()} Authorities — {raw_path.stem}",
            "",
        ]
        auth_refs: List[CanonicalAuthorityRef] = []
        rel_out = str(out_path.relative_to(self.canonical_dir))
        for rec in records:
            auth_id = rec["auth_id"] or self._mint_auth_id(domain, raw_path.stem, 1)
            title = rec["title"] or auth_id
            url = rec["url"] or "None"
            rule_text = rec["verbatim_rule"] or title
            lines.extend(
                [
                    f"## [{auth_id}] {title}",
                    f"- **Title:** {title}",
                    f"- **URL:** {url}",
                    "- **Verbatim Rule:**",
                    f"> {rule_text.replace(chr(10), chr(10) + '> ')}",
                    "",
                ]
            )
            auth_refs.append(
                CanonicalAuthorityRef(
                    auth_id=auth_id,
                    title=title,
                    url=None if url == "None" else url,
                    verbatim_quote=rule_text,
                    source_file=rel_out,
                )
            )

        out_path.write_text("\n".join(lines), encoding="utf-8")
        if auth_refs:
            self._write_toc_file(rel_out, domain, auth_refs)
        return out_path, len(records)

    def _synthesize_document_card(
        self,
        source_file: str,
        domain: str,
        auth_list: List[CanonicalAuthorityRef],
        llm: Optional[LLMProvider] = None,
    ) -> CanonicalDocumentCard:
        """Builds a Tier 1 `CanonicalDocumentCard` using LLM synthesis when available, with deterministic fallback."""
        toc_path = self._toc_path_for_source(source_file)
        toc_rel = str(toc_path.relative_to(self.canonical_dir))
        doc_title = (
            Path(source_file).stem.removesuffix(".authorities").replace("_", " ").replace("-", " ").title()
        )
        authority_tier = "statute_regulation"
        jurisdiction_scope = "General / Federal"

        # Evenly sample headings across the entire document so synopsis covers beginning, middle, end
        total = len(auth_list)
        if total <= 12:
            sampled = auth_list
        else:
            step = max(1, total // 12)
            sampled = [auth_list[i] for i in range(0, total, step)][:12]
            if auth_list[-1] not in sampled:
                sampled.append(auth_list[-1])

        fallback_headings = "; ".join(a.title for a in sampled[:6])
        if total > 6:
            fallback_headings += f" (+{total - 6} more sections)"
        synopsis = f"Covers {fallback_headings}."

        if llm is not None and auth_list:
            headings_block = "\n".join(
                f"- [{a.auth_id}] {a.title}: {a.verbatim_quote[:140].replace(chr(10), ' ')}"
                for a in sampled
            )
            prompt = (
                f"Document: `{source_file}` (domain: `{domain}`, total sections: {total}).\n"
                "Below is an evenly sampled outline across the full document:\n"
                f"{headings_block}\n\n"
                "Synthesize a `CanonicalDocumentSynopsisDraft` with clean `title`, `authority_tier`, "
                "`jurisdiction_scope`, and a concise 1-2 sentence `scope_synopsis` explaining what topics/rules "
                "this entire document governs so a Stage 1 planner knows when to inspect its Table of Contents."
            )
            try:
                draft = llm.generate_structured(
                    prompt=prompt,
                    response_model=CanonicalDocumentSynopsisDraft,
                    system_instruction=(
                        "You write compact catalog card summaries for canonical reference documents. "
                        "Stay strictly faithful to the sampled headings and previews provided."
                    ),
                )
                if draft.title.strip():
                    doc_title = draft.title.strip()
                authority_tier = draft.authority_tier
                if draft.jurisdiction_scope.strip():
                    jurisdiction_scope = draft.jurisdiction_scope.strip()
                if draft.scope_synopsis.strip():
                    synopsis = draft.scope_synopsis.strip()
            except Exception as exc:
                logger.warning("LLM card synopsis failed for %s (%s); using deterministic fallback.", source_file, exc)

        return CanonicalDocumentCard(
            doc_id=source_file,
            domain=domain,
            title=doc_title,
            authority_tier=authority_tier,
            jurisdiction_scope=jurisdiction_scope,
            scope_synopsis=synopsis,
            authority_file=source_file,
            toc_file=toc_rel,
            authority_count=total,
        )

    def rebuild_index_markdown(self, llm: Optional[LLMProvider] = None) -> Path:
        """Generates compact Tier 1 `canonical/INDEX.md`, `canonical/catalog.json`, and Tier 2 `.toc.md` files."""
        self.canonical_dir.mkdir(parents=True, exist_ok=True)
        router = CanonicalRouter(self.canonical_dir)
        authorities = router.list_authorities()

        by_source: Dict[str, List[CanonicalAuthorityRef]] = {}
        for auth in authorities.values():
            key = auth.source_file or "general/uncategorized.md"
            by_source.setdefault(key, []).append(auth)

        cards: List[CanonicalDocumentCard] = []
        for source_file, auth_list in sorted(by_source.items()):
            domain_label = Path(source_file).parts[0] if len(Path(source_file).parts) > 1 else "general"
            self._write_toc_file(source_file, domain_label, auth_list)
            cards.append(
                self._synthesize_document_card(source_file, domain_label, auth_list, llm=llm)
            )

        catalog_payload = {
            "generated_at": datetime.datetime.now(datetime.timezone.utc).isoformat(),
            "document_count": len(cards),
            "total_authorities": len(authorities),
            "documents": [c.model_dump() for c in cards],
        }
        (self.canonical_dir / "catalog.json").write_text(
            json.dumps(catalog_payload, indent=2), encoding="utf-8"
        )

        lines: List[str] = [
            "# Canonical Knowledge Catalog `(b)`",
            "",
            "High-level Document Card Catalog of standing controlling authorities, statutory rules, and rubrics.",
            "To inspect sections inside a document, call `browse_canonical_toc(doc_id)` or `search_canonical_authorities(query, doc_id=...)`.",
            "",
            "| Domain | Document ID | Tier | Scope | Sections | TOC File | Scope Synopsis |",
            "| :--- | :--- | :--- | :--- | ---: | :--- | :--- |",
        ]
        for card in cards:
            safe_syn = card.scope_synopsis.replace("\n", " ").replace("|", "/").strip()
            safe_scope = card.jurisdiction_scope.replace("|", "/").strip()
            lines.append(
                f"| `{card.domain}` | `{card.doc_id}` | `{card.authority_tier}` | {safe_scope} | {card.authority_count} | `{card.toc_file}` | {safe_syn} |"
            )

        lines.append("")
        for card in cards:
            lines.extend(
                [
                    f"## `{card.doc_id}` — {card.title}",
                    f"- **Domain:** `{card.domain}` | **Tier:** `{card.authority_tier}` | **Scope:** {card.jurisdiction_scope}",
                    f"- **Authority File:** `{card.authority_file}` | **Authorities:** {card.authority_count} | **TOC:** `{card.toc_file}`",
                    f"- **Scope Synopsis:** {card.scope_synopsis}",
                    "",
                ]
            )

        index_path = self.canonical_dir / "INDEX.md"
        index_path.write_text("\n".join(lines), encoding="utf-8")
        return index_path

    def ingest_corpus(
        self, purge_encoded: bool = False, llm: Optional[LLMProvider] = None
    ) -> Dict[str, Any]:
        """Encodes raw canonical corpus files into 3-tier Markdown/JSON artifacts and rebuilds `INDEX.md`.

        Discovers raw files in `canonical/raw/<domain>/` as well as any un-anchored raw
        files (non-generated files lacking `[AUTH:...]` anchors) dropped directly under
        `canonical/<domain>/`. When `purge_encoded=True`, deletes previously generated
        domain `.md`, `.toc.md`, `catalog.json`, and `INDEX.md` files (preserving
        `canonical/raw/` and any un-anchored user source files) before regenerating.

        Args:
            purge_encoded: If True, removes stale generated canonical `.md`, `.toc.md`,
                `catalog.json`, and `INDEX.md` files before encoding.
            llm: Optional `LLMProvider` to synthesize full-document `scope_synopsis`
                entries in Tier 1 `INDEX.md` and `catalog.json`. Falls back to
                evenly sampled section headings when `None`.

        Returns:
            Summary dictionary with processed files, generated paths, and authority counts.
        """
        self.canonical_dir.mkdir(parents=True, exist_ok=True)
        self.raw_dir.mkdir(parents=True, exist_ok=True)

        purged_files: List[str] = []
        if purge_encoded:
            for root_artifact in ("INDEX.md", "catalog.json"):
                art_path = self.canonical_dir / root_artifact
                if art_path.exists():
                    art_path.unlink()
                    purged_files.append(root_artifact)
            for md_path in sorted(self.canonical_dir.rglob("*.md")):
                rel_parts = md_path.relative_to(self.canonical_dir).parts
                if "raw" in rel_parts:
                    continue
                text = md_path.read_text(encoding="utf-8")
                if (
                    md_path.name.endswith(".toc.md")
                    or CANONICAL_GENERATED_MARKER in text
                    or AUTH_HEADING_RE.search(text)
                ):
                    # Preserve user raw files only if they have no [AUTH:] tags and no generated marker
                    rel_str = str(md_path.relative_to(self.canonical_dir))
                    md_path.unlink()
                    purged_files.append(rel_str)

        processed_files: List[Dict[str, Any]] = []

        # 1. Process canonical/raw/<domain>/<file>
        for raw_path in sorted(self.raw_dir.rglob("*")):
            if not raw_path.is_file() or raw_path.suffix.lower() not in SUPPORTED_CANONICAL_EXTENSIONS:
                continue
            rel_to_raw = raw_path.relative_to(self.raw_dir)
            domain = self._slugify(rel_to_raw.parts[0] if len(rel_to_raw.parts) > 1 else "general")
            rel_source = str(raw_path.relative_to(self.canonical_dir))
            out_path, count = self._encode_single_file(raw_path, domain, rel_source)
            if count > 0:
                processed_files.append(
                    {
                        "raw": rel_source,
                        "encoded": str(out_path.relative_to(self.canonical_dir)),
                        "toc": str(self._toc_path_for_source(str(out_path.relative_to(self.canonical_dir))).relative_to(self.canonical_dir)),
                        "domain": domain,
                        "authorities_encoded": count,
                    }
                )

        # 2. Also process any un-anchored raw files dropped directly into canonical/<domain>/
        for direct_path in sorted(self.canonical_dir.rglob("*")):
            if not direct_path.is_file() or direct_path.name == "INDEX.md":
                continue
            rel_parts = direct_path.relative_to(self.canonical_dir).parts
            if "raw" in rel_parts or direct_path.suffix.lower() not in SUPPORTED_CANONICAL_EXTENSIONS:
                continue
            if direct_path.name.endswith(".authorities.md") or direct_path.name.endswith(".toc.md"):
                continue
            if direct_path.suffix.lower() == ".md":
                text = direct_path.read_text(encoding="utf-8")
                if CANONICAL_GENERATED_MARKER in text or AUTH_HEADING_RE.search(text):
                    continue
            domain = self._slugify(rel_parts[0] if len(rel_parts) > 1 else "general")
            rel_source = str(direct_path.relative_to(self.canonical_dir))
            out_path, count = self._encode_single_file(direct_path, domain, rel_source)
            if count > 0:
                processed_files.append(
                    {
                        "raw": rel_source,
                        "encoded": str(out_path.relative_to(self.canonical_dir)),
                        "toc": str(self._toc_path_for_source(str(out_path.relative_to(self.canonical_dir))).relative_to(self.canonical_dir)),
                        "domain": domain,
                        "authorities_encoded": count,
                    }
                )

        index_path = self.rebuild_index_markdown(llm=llm)
        total_authorities = len(CanonicalRouter(self.canonical_dir).list_authorities())
        summary = {
            "ingested_at": datetime.datetime.now(datetime.timezone.utc).isoformat(),
            "purge_encoded": purge_encoded,
            "purged_files": purged_files,
            "files_processed": len(processed_files),
            "total_authorities": total_authorities,
            "index_path": str(index_path),
            "catalog_path": str(self.canonical_dir / "catalog.json"),
            "files": processed_files,
        }
        logger.info(
            "Canonical corpus ingested: files=%d total_authorities=%d",
            len(processed_files),
            total_authorities,
        )
        return summary

    def get_corpus_status(self) -> Dict[str, Any]:
        """Returns current `INDEX.md`, document catalog cards, active authorities, and raw source inventory."""
        router = CanonicalRouter(self.canonical_dir)
        authorities = [a.model_dump() for a in router.list_authorities().values()]
        catalog_path = self.canonical_dir / "catalog.json"
        catalog: Dict[str, Any] = {}
        if catalog_path.exists():
            try:
                catalog = json.loads(catalog_path.read_text(encoding="utf-8"))
            except json.JSONDecodeError:
                catalog = {}
        raw_domains: Dict[str, List[str]] = {}
        if self.raw_dir.exists():
            for raw_path in sorted(self.raw_dir.rglob("*")):
                if raw_path.is_file():
                    rel_parts = raw_path.relative_to(self.raw_dir).parts
                    dom = rel_parts[0] if len(rel_parts) > 1 else "general"
                    raw_domains.setdefault(dom, []).append(raw_path.name)
        return {
            "index_markdown": router.get_index_markdown(),
            "catalog": catalog,
            "total_authorities": len(authorities),
            "authorities": authorities,
            "raw_domains": raw_domains,
        }


class MatterIngestor:
    """Deterministic file parser and search tool builder for project inputs `(a)`."""

    def __init__(self, matters_root: Path) -> None:
        """Initializes the matter ingestor.

        Args:
            matters_root: Root directory containing per-matter folders (`matters/<id>`).
        """
        self.matters_root = matters_root

    def _matter_dirs(self, matter_id: str) -> Tuple[Path, Path, Path, Path]:
        """Returns `(matter_dir, raw_dir, indexed_dir, bundles_dir)` for a matter."""
        matter_dir = self.matters_root / matter_id
        raw_dir = matter_dir / "inputs" / "raw"
        indexed_dir = matter_dir / "inputs" / "indexed"
        bundles_dir = matter_dir / "bundles"
        return matter_dir, raw_dir, indexed_dir, bundles_dir

    def create_matter(self, matter_id: str) -> Path:
        """Creates the standard `inputs/raw`, `inputs/indexed`, and `bundles` directories."""
        matter_dir, raw_dir, indexed_dir, bundles_dir = self._matter_dirs(matter_id)
        raw_dir.mkdir(parents=True, exist_ok=True)
        indexed_dir.mkdir(parents=True, exist_ok=True)
        bundles_dir.mkdir(parents=True, exist_ok=True)
        return matter_dir

    def list_matters(self) -> List[Dict[str, Any]]:
        """Lists all project matters on disk along with their raw and indexed file counts."""
        if not self.matters_root.exists():
            return []
        results: List[Dict[str, Any]] = []
        for entry in sorted(self.matters_root.iterdir()):
            if not entry.is_dir():
                continue
            matter_id = entry.name
            _, raw_dir, indexed_dir, bundles_dir = self._matter_dirs(matter_id)
            raw_files = (
                sorted(p.name for p in raw_dir.iterdir() if p.is_file())
                if raw_dir.exists()
                else []
            )
            manifest_path = indexed_dir / "manifest.json"
            manifest = (
                json.loads(manifest_path.read_text(encoding="utf-8"))
                if manifest_path.exists()
                else None
            )
            bundle_files = (
                sorted(p.stem for p in bundles_dir.glob("*.json"))
                if bundles_dir.exists()
                else []
            )
            results.append(
                {
                    "matter_id": matter_id,
                    "raw_files": raw_files,
                    "indexed": manifest is not None,
                    "manifest": manifest,
                    "saved_bundles": bundle_files,
                }
            )
        return results

    def ingest_pdf(self, raw_path: Path, indexed_dir: Path) -> Tuple[Path, int]:
        """Extracts coordinate-stamped paragraph blocks from a PDF using `pdfplumber`.

        Groups extracted words into line-level blocks separated by vertical gaps,
        computing integer `[x1, y1, x2, y2]` bounding boxes and embedding a
        `<!-- LOCATOR: {...} -->` header above each block.

        Args:
            raw_path: Path to the source `.pdf` file.
            indexed_dir: Target directory for `<filename>.indexed.md`.

        Returns:
            Tuple of `(output_markdown_path, block_count)`.
        """
        file_hash = _sha256_short(raw_path.read_bytes())
        stem = re.sub(r"[^A-Za-z0-9_-]+", "_", raw_path.stem).upper()
        md_blocks: List[str] = [f"# Indexed Document: {raw_path.name}\n"]
        block_count = 0

        with pdfplumber.open(raw_path) as pdf:
            for page_idx, page in enumerate(pdf.pages, start=1):
                words = page.extract_words() or []
                if not words:
                    plain_text = (page.extract_text() or "").strip()
                    if plain_text:
                        block_count += 1
                        loc = SourceLocator(
                            source_type="pdf",
                            file_name=raw_path.name,
                            page=page_idx,
                            bounding_box=[0, 0, int(page.width), int(page.height)],
                            locator_key=f"{stem}-P{page_idx}-B1",
                            payload_hash=file_hash,
                        )
                        md_blocks.append(
                            f"<!-- LOCATOR: {loc.model_dump_json(exclude_none=True)} -->\n"
                            f"{plain_text}\n"
                        )
                    continue

                # Group words into visual lines (tolerance 4pt) and then paragraphs
                # separated by larger vertical gaps (> 18pt) so bounding boxes
                # tightly enclose coherent evidentiary passages.
                sorted_words = sorted(words, key=lambda w: (round(float(w["top"]), 1), float(w["x0"])))
                lines: List[List[Dict[str, Any]]] = []
                for word in sorted_words:
                    if not lines or abs(float(word["top"]) - float(lines[-1][0]["top"])) > 4.0:
                        lines.append([word])
                    else:
                        lines[-1].append(word)

                paragraphs: List[List[List[Dict[str, Any]]]] = []
                for line in lines:
                    line.sort(key=lambda w: float(w["x0"]))
                    if not paragraphs:
                        paragraphs.append([line])
                    else:
                        prev_bottom = max(float(w["bottom"]) for w in paragraphs[-1][-1])
                        curr_top = min(float(w["top"]) for w in line)
                        if (curr_top - prev_bottom) > 18.0:
                            paragraphs.append([line])
                        else:
                            paragraphs[-1].append(line)

                for b_idx, para in enumerate(paragraphs, start=1):
                    flat_words = [w for ln in para for w in ln]
                    text = " ".join(" ".join(w["text"] for w in ln) for ln in para).strip()
                    if not text:
                        continue
                    x1 = int(min(float(w["x0"]) for w in flat_words))
                    y1 = int(min(float(w["top"]) for w in flat_words))
                    x2 = int(max(float(w["x1"]) for w in flat_words))
                    y2 = int(max(float(w["bottom"]) for w in flat_words))
                    block_count += 1
                    loc = SourceLocator(
                        source_type="pdf",
                        file_name=raw_path.name,
                        page=page_idx,
                        bounding_box=[x1, y1, x2, y2],
                        locator_key=f"{stem}-P{page_idx}-B{b_idx}",
                        payload_hash=file_hash,
                    )
                    md_blocks.append(
                        f"<!-- LOCATOR: {loc.model_dump_json(exclude_none=True)} -->\n{text}\n"
                    )

        out_path = indexed_dir / f"{raw_path.name}.indexed.md"
        out_path.write_text("\n".join(md_blocks), encoding="utf-8")
        return out_path, block_count

    def ingest_markdown(self, raw_path: Path, indexed_dir: Path) -> Tuple[Path, int]:
        """Splits a Markdown/text file into paragraph blocks stamped with locators."""
        content = raw_path.read_text(encoding="utf-8")
        file_hash = _sha256_short(content.encode("utf-8"))
        stem = re.sub(r"[^A-Za-z0-9_-]+", "_", raw_path.stem).upper()
        paragraphs = [p.strip() for p in re.split(r"\n\s*\n", content) if p.strip()]
        md_blocks: List[str] = [f"# Indexed Document: {raw_path.name}\n"]

        for idx, para in enumerate(paragraphs, start=1):
            loc = SourceLocator(
                source_type="markdown",
                file_name=raw_path.name,
                locator_key=f"{stem}-SEC-{idx}",
                payload_hash=file_hash,
            )
            md_blocks.append(
                f"<!-- LOCATOR: {loc.model_dump_json(exclude_none=True)} -->\n{para}\n"
            )

        out_path = indexed_dir / f"{raw_path.name}.indexed.md"
        out_path.write_text("\n".join(md_blocks), encoding="utf-8")
        return out_path, len(paragraphs)

    def ingest_spreadsheet(self, raw_path: Path) -> List[Dict[str, Any]]:
        """Extracts cell coordinates, row line-item labels, formulas, and evaluated values.

        Performs a dual pass on `.xlsx` workbooks (`data_only=False` for formula strings
        and `data_only=True` for evaluated cached values) and also supports `.csv`.

        Args:
            raw_path: Path to `.xlsx`, `.xlsm`, or `.csv` file.

        Returns:
            List of cell index records ready for `sheets_index.jsonl`.
        """
        file_hash = _sha256_short(raw_path.read_bytes())
        entries: List[Dict[str, Any]] = []

        if raw_path.suffix.lower() == ".csv":
            with raw_path.open("r", encoding="utf-8", newline="") as f:
                reader = csv.reader(f)
                for r_idx, row in enumerate(reader, start=1):
                    row_label = row[0].strip() if row else ""
                    for c_idx, val in enumerate(row, start=1):
                        cleaned = val.strip()
                        if not cleaned:
                            continue
                        col_letter = openpyxl.utils.get_column_letter(c_idx)
                        coord = f"{col_letter}{r_idx}"
                        parsed_val: Any = cleaned
                        try:
                            parsed_val = float(cleaned) if "." in cleaned else int(cleaned)
                        except ValueError:
                            pass
                        loc = SourceLocator(
                            source_type="spreadsheet",
                            file_name=raw_path.name,
                            sheet="CSV",
                            cell_range=coord,
                            raw_value=parsed_val,
                            payload_hash=file_hash,
                        )
                        entries.append(
                            {
                                "file_name": raw_path.name,
                                "sheet": "CSV",
                                "cell_range": coord,
                                "line_item": row_label or coord,
                                "display": cleaned,
                                "raw_value": parsed_val,
                                "formula": None,
                                "locator": loc.model_dump(exclude_none=True),
                            }
                        )
            return entries

        wb_formulas = openpyxl.load_workbook(raw_path, data_only=False)
        wb_values = openpyxl.load_workbook(raw_path, data_only=True)

        for sheet_name in wb_formulas.sheetnames:
            ws_f = wb_formulas[sheet_name]
            ws_v = wb_values[sheet_name]
            for row_idx in range(1, ws_f.max_row + 1):
                first_cell_val = ws_v.cell(row=row_idx, column=1).value
                if first_cell_val is None:
                    first_cell_val = ws_f.cell(row=row_idx, column=1).value
                row_label = str(first_cell_val).strip() if first_cell_val is not None else ""

                for col_idx in range(1, ws_f.max_column + 1):
                    cell_f = ws_f.cell(row=row_idx, column=col_idx)
                    cell_v = ws_v.cell(row=row_idx, column=col_idx)
                    raw_expr = cell_f.value
                    eval_val = cell_v.value
                    if raw_expr is None and eval_val is None:
                        continue

                    formula_str = (
                        str(raw_expr)
                        if isinstance(raw_expr, str) and raw_expr.startswith("=")
                        else None
                    )
                    primitive = eval_val if eval_val is not None else raw_expr
                    coord = cell_f.coordinate
                    loc = SourceLocator(
                        source_type="spreadsheet",
                        file_name=raw_path.name,
                        sheet=sheet_name,
                        cell_range=coord,
                        raw_value=primitive,
                        payload_hash=file_hash,
                    )
                    entries.append(
                        {
                            "file_name": raw_path.name,
                            "sheet": sheet_name,
                            "cell_range": coord,
                            "line_item": row_label or coord,
                            "display": str(primitive),
                            "raw_value": primitive,
                            "formula": formula_str,
                            "locator": loc.model_dump(exclude_none=True),
                        }
                    )

        return entries

    def ingest_matter(self, matter_id: str) -> Dict[str, Any]:
        """Deterministically ingests all raw files for a matter into `inputs/indexed/`.

        Args:
            matter_id: Project/matter slug under `matters/`.

        Returns:
            Summary manifest dictionary written to `inputs/indexed/manifest.json`.
        """
        _, raw_dir, indexed_dir, _ = self._matter_dirs(matter_id)
        indexed_dir.mkdir(parents=True, exist_ok=True)
        if not raw_dir.exists():
            raw_dir.mkdir(parents=True, exist_ok=True)

        # Clean stale indexed markdown/jsonl artifacts before regenerating
        for old_file in indexed_dir.glob("*.indexed.md"):
            old_file.unlink()

        sheet_entries: List[Dict[str, Any]] = []
        indexed_files: List[Dict[str, Any]] = []

        for raw_path in sorted(raw_dir.iterdir()):
            if not raw_path.is_file():
                continue
            suffix = raw_path.suffix.lower()
            if suffix == ".pdf":
                out_path, count = self.ingest_pdf(raw_path, indexed_dir)
                indexed_files.append(
                    {"raw": raw_path.name, "indexed": out_path.name, "blocks": count}
                )
            elif suffix in (".xlsx", ".xlsm", ".csv"):
                rows = self.ingest_spreadsheet(raw_path)
                sheet_entries.extend(rows)
                indexed_files.append(
                    {"raw": raw_path.name, "indexed": "sheets_index.jsonl", "cells": len(rows)}
                )
            elif suffix in (".md", ".txt"):
                out_path, count = self.ingest_markdown(raw_path, indexed_dir)
                indexed_files.append(
                    {"raw": raw_path.name, "indexed": out_path.name, "blocks": count}
                )
            else:
                logger.info("Skipping unsupported file type during ingest: %s", raw_path.name)

        sheets_path = indexed_dir / "sheets_index.jsonl"
        sheets_path.write_text(
            "\n".join(json.dumps(r, ensure_ascii=False, default=str) for r in sheet_entries)
            + ("\n" if sheet_entries else ""),
            encoding="utf-8",
        )

        manifest = {
            "matter_id": matter_id,
            "ingested_at": datetime.datetime.now(datetime.timezone.utc).isoformat(),
            "files_processed": len(indexed_files),
            "spreadsheet_cells_indexed": len(sheet_entries),
            "files": indexed_files,
        }
        (indexed_dir / "manifest.json").write_text(
            json.dumps(manifest, indent=2), encoding="utf-8"
        )
        logger.info(
            "Ingested matter=%s files=%d sheet_cells=%d",
            matter_id,
            len(indexed_files),
            len(sheet_entries),
        )
        return manifest

    def _load_indexed_blocks(self, matter_id: str) -> List[Dict[str, Any]]:
        """Parses all `*.indexed.md` files for a matter into structured block dictionaries."""
        _, _, indexed_dir, _ = self._matter_dirs(matter_id)
        blocks: List[Dict[str, Any]] = []
        if not indexed_dir.exists():
            return blocks

        for md_path in sorted(indexed_dir.glob("*.indexed.md")):
            lines = md_path.read_text(encoding="utf-8").splitlines()
            curr_locator: Optional[Dict[str, Any]] = None
            curr_lines: List[str] = []

            def flush_block() -> None:
                if curr_locator is not None:
                    blocks.append(
                        {
                            "indexed_file": md_path.name,
                            "locator": curr_locator,
                            "text": "\n".join(curr_lines).strip(),
                        }
                    )

            for line in lines:
                m = LOCATOR_COMMENT_RE.match(line.strip())
                if m:
                    flush_block()
                    curr_locator = json.loads(m.group(1))
                    curr_lines = []
                elif curr_locator is not None:
                    curr_lines.append(line)
            flush_block()

        return blocks

    def expand_locator_context(
        self, matter_id: str, locators: List[SourceLocator], window: int = 1
    ) -> str:
        """Collects surrounding document blocks/rows for Stage 4 congruence auditing."""
        blocks = self._load_indexed_blocks(matter_id)
        _, _, indexed_dir, _ = self._matter_dirs(matter_id)
        sheets_path = indexed_dir / "sheets_index.jsonl"
        sheet_rows = (
            [json.loads(line) for line in sheets_path.read_text(encoding="utf-8").splitlines() if line.strip()]
            if sheets_path.exists()
            else []
        )

        snippets: List[str] = []
        seen_keys: set[str] = set()

        for loc in locators:
            if loc.locator_key:
                for idx, blk in enumerate(blocks):
                    if blk["locator"].get("locator_key") == loc.locator_key:
                        start = max(0, idx - window)
                        end = min(len(blocks), idx + window + 1)
                        for neighbor in blocks[start:end]:
                            n_key = str(neighbor["locator"].get("locator_key"))
                            if n_key not in seen_keys:
                                seen_keys.add(n_key)
                                snippets.append(
                                    f"[{n_key} | {neighbor['locator'].get('file_name')} p.{neighbor['locator'].get('page', '-')}]\n"
                                    f"{neighbor['text']}"
                                )
            elif loc.source_type == "spreadsheet" and loc.file_name:
                matching = [
                    r
                    for r in sheet_rows
                    if r["file_name"] == loc.file_name and (not loc.sheet or r["sheet"] == loc.sheet)
                ]
                if matching:
                    snippets.append(
                        f"[Spreadsheet {loc.file_name} ! {loc.sheet}]\n"
                        + "\n".join(
                            f"  {r['cell_range']}: {r['line_item']} = {r['display']} (fx: {r['formula']})"
                            for r in matching[:25]
                        )
                    )

        return "\n\n".join(snippets)

    def build_stage2_tools(self, matter_id: str) -> List[ToolDefinition]:
        """Constructs deterministic search & read tools for the Stage 2 Fact Harvester.

        Args:
            matter_id: Target matter directory identifier.

        Returns:
            List of `ToolDefinition` instances safe to expose to an LLM agent.
        """
        _, raw_dir, indexed_dir, _ = self._matter_dirs(matter_id)

        def list_matter_files() -> Dict[str, Any]:
            manifest_path = indexed_dir / "manifest.json"
            if manifest_path.exists():
                manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
                return {
                    "matter_id": matter_id,
                    "files": [
                        {"raw_file": f["raw"], **f} for f in manifest.get("files", [])
                    ],
                }
            raw_files = (
                [{"raw_file": p.name} for p in sorted(raw_dir.iterdir()) if p.is_file()]
                if raw_dir.exists()
                else []
            )
            return {"matter_id": matter_id, "files": raw_files}

        def grep_indexed_inputs(pattern: str, max_results: int = 10) -> Dict[str, Any]:
            blocks = self._load_indexed_blocks(matter_id)
            regex = re.compile(re.escape(pattern), re.IGNORECASE)
            matches: List[Dict[str, Any]] = []
            for blk in blocks:
                if regex.search(blk["text"]):
                    matches.append(
                        {
                            "locator": blk["locator"],
                            "excerpt": blk["text"],
                        }
                    )
                    if len(matches) >= max_results:
                        break
            return {"pattern": pattern, "match_count": len(matches), "matches": matches}

        def read_locator_context(locator_key: str, window_blocks: int = 1) -> Dict[str, Any]:
            blocks = self._load_indexed_blocks(matter_id)
            for idx, blk in enumerate(blocks):
                if blk["locator"].get("locator_key") == locator_key:
                    start = max(0, idx - window_blocks)
                    end = min(len(blocks), idx + window_blocks + 1)
                    return {
                        "locator": blk["locator"],
                        "block_text": blk["text"],
                        "surrounding_blocks": [
                            {"locator": b["locator"], "text": b["text"]}
                            for b in blocks[start:end]
                        ],
                    }
            return {"error": f"No indexed block found with locator_key='{locator_key}'."}

        def search_spreadsheet_cells(query: str, max_results: int = 20) -> Dict[str, Any]:
            sheets_path = indexed_dir / "sheets_index.jsonl"
            if not sheets_path.exists():
                return {"query": query, "cells": []}
            q_lower = query.lower()
            matched: List[Dict[str, Any]] = []
            for line in sheets_path.read_text(encoding="utf-8").splitlines():
                if not line.strip():
                    continue
                row = json.loads(line)
                haystack = " ".join(
                    str(row.get(k, ""))
                    for k in ("file_name", "sheet", "cell_range", "line_item", "display", "formula")
                ).lower()
                if q_lower in haystack or q_lower == "*":
                    matched.append(row)
                    if len(matched) >= max_results:
                        break
            return {"query": query, "cells": matched}

        return [
            ToolDefinition(
                name="list_matter_files",
                description="List all raw and coordinate-indexed files available in this project matter.",
                parameters_schema={"type": "object", "properties": {}},
                handler=list_matter_files,
            ),
            ToolDefinition(
                name="grep_indexed_inputs",
                description=(
                    "Case-insensitive search across all coordinate-stamped PDF and Markdown blocks "
                    "for this matter. Returns exact pre-computed `locator` objects and block text."
                ),
                parameters_schema={
                    "type": "object",
                    "properties": {
                        "pattern": {
                            "type": "string",
                            "description": "Keyword or phrase to search for.",
                        },
                        "max_results": {
                            "type": "integer",
                            "description": "Maximum blocks to return (default 10).",
                        },
                    },
                    "required": ["pattern"],
                },
                handler=grep_indexed_inputs,
            ),
            ToolDefinition(
                name="read_locator_context",
                description=(
                    "Reads the full text and surrounding blocks for a specific `locator_key` "
                    "to check for exceptions, qualifiers, or footnotes."
                ),
                parameters_schema={
                    "type": "object",
                    "properties": {
                        "locator_key": {
                            "type": "string",
                            "description": "Exact `locator_key` returned by grep_indexed_inputs.",
                        },
                        "window_blocks": {
                            "type": "integer",
                            "description": "Number of adjacent blocks before/after to include.",
                        },
                    },
                    "required": ["locator_key"],
                },
                handler=read_locator_context,
            ),
            ToolDefinition(
                name="search_spreadsheet_cells",
                description=(
                    "Searches indexed Excel/CSV cells by line item, sheet name, cell coordinate, "
                    "or formula. Returns exact `sheet`, `cell_range`, `formula`, `raw_value`, and `locator`."
                ),
                parameters_schema={
                    "type": "object",
                    "properties": {
                        "query": {
                            "type": "string",
                            "description": "Keyword or metric name (e.g., 'Gross Margin', 'Total', or '*' for sample rows).",
                        },
                        "max_results": {
                            "type": "integer",
                            "description": "Maximum cells to return (default 20).",
                        },
                    },
                    "required": ["query"],
                },
                handler=search_spreadsheet_cells,
            ),
        ]

    @staticmethod
    def _values_match(quote: Optional[str], cell_row: Dict[str, Any]) -> bool:
        """Checks whether a spreadsheet quote matches the indexed cell's display, raw_value, or formula."""
        norm_q = _normalize_for_match(quote)
        if not norm_q:
            return True
        candidates = [
            cell_row.get("display"),
            cell_row.get("raw_value"),
            cell_row.get("formula"),
            cell_row.get("line_item"),
        ]
        for cand in candidates:
            if cand is None:
                continue
            norm_c = _normalize_for_match(str(cand))
            if norm_c and (norm_c in norm_q or norm_q in norm_c):
                return True
        # Handle formatted currency / commas / trailing decimals vs numeric raw_value (e.g. "$42,150.00" vs 42150.0)
        raw_val = cell_row.get("raw_value")
        if isinstance(raw_val, (int, float)) and not isinstance(raw_val, bool):
            stripped_q = re.sub(r"[,$%\s]", "", (quote or "").strip())
            try:
                if abs(float(stripped_q) - float(raw_val)) < 1e-6:
                    return True
            except ValueError:
                pass
        return False

    def verify_and_hydrate_ledger(
        self, matter_id: str, ledger: VerifiedFactLedger
    ) -> Tuple[VerifiedFactLedger, List[str]]:
        """Programmatically verifies Stage 2 `VerifiedFact.locator` entries against indexed files on disk.

        Hydrates `payload_hash`, `page`, `file_name`, and `raw_value` from disk when matched.
        Unverifiable facts (missing locator keys/cells or non-matching quotes when indexed
        files exist) are moved to `ledger.unresolved_gaps` with explanatory warnings.
        """
        _, _, indexed_dir, _ = self._matter_dirs(matter_id)
        blocks = self._load_indexed_blocks(matter_id)
        block_by_key: Dict[str, Dict[str, Any]] = {}
        for blk in blocks:
            lk = blk.get("locator", {}).get("locator_key")
            if lk:
                block_by_key[str(lk)] = blk

        sheet_rows: List[Dict[str, Any]] = []
        sheets_path = indexed_dir / "sheets_index.jsonl"
        if sheets_path.exists():
            for line in sheets_path.read_text(encoding="utf-8").splitlines():
                if line.strip():
                    sheet_rows.append(json.loads(line))

        cells_by_full: Dict[Tuple[str, str, str], Dict[str, Any]] = {}
        cells_by_file_coord: Dict[Tuple[str, str], Dict[str, Any]] = {}
        for row in sheet_rows:
            fn = str(row.get("file_name", ""))
            sh = str(row.get("sheet", ""))
            cr = str(row.get("cell_range", ""))
            cells_by_full[(fn, sh, cr)] = row
            cells_by_file_coord[(fn, cr)] = row

        # If no indexed files exist at all (e.g. synthetic test fixture), skip dropping
        if not block_by_key and not sheet_rows:
            return ledger, []

        kept_facts = []
        warnings: List[str] = []

        for fact in ledger.verified_facts:
            loc = fact.locator
            if loc.locator_key:
                blk = block_by_key.get(loc.locator_key)
                if blk is None:
                    msg = (
                        f"Dropped unverified fact '{fact.fact_id}': locator_key "
                        f"'{loc.locator_key}' does not exist in indexed matter files."
                    )
                    warnings.append(msg)
                    ledger.unresolved_gaps.append(
                        UnresolvedGapItem(
                            query=fact.fact_id,
                            recommended_handling="assumption",
                            rationale=msg,
                        )
                    )
                    continue
                disk_loc = blk["locator"]
                norm_block = _normalize_for_match(blk.get("text"))
                norm_quote = _normalize_for_match(fact.quote)
                if norm_quote and norm_block and norm_quote not in norm_block and norm_block not in norm_quote:
                    msg = (
                        f"Dropped unverified fact '{fact.fact_id}': quote did not match text at "
                        f"locator_key '{loc.locator_key}'."
                    )
                    warnings.append(msg)
                    ledger.unresolved_gaps.append(
                        UnresolvedGapItem(
                            query=fact.fact_id,
                            recommended_handling="assumption",
                            rationale=msg,
                        )
                    )
                    continue
                # Hydrate canonical disk metadata onto locator
                hydrated_loc = loc.model_copy(
                    update={
                        "file_name": disk_loc.get("file_name") or loc.file_name,
                        "page": disk_loc.get("page") if disk_loc.get("page") is not None else loc.page,
                        "payload_hash": disk_loc.get("payload_hash") or loc.payload_hash,
                    }
                )
                kept_facts.append(fact.model_copy(update={"locator": hydrated_loc}))
                continue

            if loc.cell_range:
                row = None
                if loc.file_name and loc.sheet:
                    row = cells_by_full.get((loc.file_name, loc.sheet, loc.cell_range))
                if row is None and loc.file_name:
                    row = cells_by_file_coord.get((loc.file_name, loc.cell_range))
                if row is None:
                    msg = (
                        f"Dropped unverified fact '{fact.fact_id}': spreadsheet cell "
                        f"'{loc.file_name}:{loc.sheet or ''}!{loc.cell_range}' not found in sheets_index.jsonl."
                    )
                    warnings.append(msg)
                    ledger.unresolved_gaps.append(
                        UnresolvedGapItem(
                            query=fact.fact_id,
                            recommended_handling="assumption",
                            rationale=msg,
                        )
                    )
                    continue
                if not self._values_match(fact.quote, row):
                    msg = (
                        f"Dropped unverified fact '{fact.fact_id}': quote '{fact.quote}' did not match "
                        f"indexed cell value '{row.get('display')}'."
                    )
                    warnings.append(msg)
                    ledger.unresolved_gaps.append(
                        UnresolvedGapItem(
                            query=fact.fact_id,
                            recommended_handling="assumption",
                            rationale=msg,
                        )
                    )
                    continue
                disk_loc = row.get("locator", {})
                hydrated_loc = loc.model_copy(
                    update={
                        "file_name": disk_loc.get("file_name") or loc.file_name,
                        "sheet": disk_loc.get("sheet") or loc.sheet,
                        "raw_value": disk_loc.get("raw_value") if disk_loc.get("raw_value") is not None else loc.raw_value,
                        "payload_hash": disk_loc.get("payload_hash") or loc.payload_hash,
                    }
                )
                kept_facts.append(fact.model_copy(update={"locator": hydrated_loc}))
                continue

            # Fact has neither locator_key nor cell_range when indexed corpus exists
            msg = f"Dropped unverified fact '{fact.fact_id}': missing locator_key and cell_range."
            warnings.append(msg)
            ledger.unresolved_gaps.append(
                UnresolvedGapItem(
                    query=fact.fact_id,
                    recommended_handling="assumption",
                    rationale=msg,
                )
            )

        if warnings:
            logger.warning("MatterIngestor ledger verification flagged %d issues for %s", len(warnings), matter_id)

        updated_ledger = ledger.model_copy(update={"verified_facts": kept_facts})
        return updated_ledger, warnings

    @staticmethod
    def verify_section_citations(
        draft: SectionOutput,
        ledger: VerifiedFactLedger,
        governing_authorities: List[CanonicalAuthorityRef],
    ) -> List[str]:
        """Programmatically verifies every `L1` evidence locator and `L2` authority citation in a draft.

        Returns an empty list when all citations verify cleanly, or descriptive errors
        for `Stage 3` self-correction retries.
        """
        errors: List[str] = []

        # 1. Index verified L1 facts from ledger (allow multiple facts per locator_key/cell)
        facts_by_key: Dict[str, List[Any]] = {}
        facts_by_cell: Dict[Tuple[str, str], List[Any]] = {}
        for fact in ledger.verified_facts:
            if fact.locator.locator_key:
                facts_by_key.setdefault(fact.locator.locator_key, []).append(fact)
            if fact.locator.cell_range:
                facts_by_cell.setdefault((fact.locator.file_name, fact.locator.cell_range), []).append(fact)

        available_hints = [
            f"{f.locator.model_dump(exclude_none=True)} -> '{(f.quote or '')[:60]}'"
            for f in ledger.verified_facts[:8]
        ]

        # 2. Index hydrated L2 governing authorities (merged with ledger.additional_authorities)
        auth_map: Dict[str, CanonicalAuthorityRef] = {}
        for auth in list(governing_authorities) + list(ledger.additional_authorities):
            auth_map[auth.auth_id] = auth

        def _check_evidence_node(node: Any, label: str) -> None:
            loc = node.locator
            if loc is None:
                nq = _normalize_for_match(node.quote)
                suggested_fact = None
                if nq:
                    for f in ledger.verified_facts:
                        nf = _normalize_for_match(f.quote)
                        if nf and (nq in nf or nf in nq):
                            suggested_fact = f
                            break
                hint = (
                    f" Set `fact_id`: \"{suggested_fact.fact_id}\" and copy `locator`: "
                    f"{json.dumps(suggested_fact.locator.model_dump(exclude_none=True))}"
                    if suggested_fact is not None
                    else f" Valid ledger facts/locators: {'; '.join(available_hints)}"
                )
                errors.append(
                    f"{label} '{node.title}' is type='evidence' without a locator."
                    f"{hint} (Or change type to 'assumption'/'reasoning' if stating an evidentiary gap.)"
                )
            elif loc.locator_key:
                matched_facts = facts_by_key.get(loc.locator_key)
                if not matched_facts:
                    errors.append(
                        f"{label} cites locator_key '{loc.locator_key}' "
                        "which is not present in the VerifiedFactLedger."
                        f" Valid ledger locators: {'; '.join(available_hints)}"
                    )
                else:
                    nq = _normalize_for_match(node.quote)
                    quote_ok = not nq or any(
                        (nf := _normalize_for_match(f.quote)) and (nq in nf or nf in nq)
                        for f in matched_facts
                    )
                    if not quote_ok:
                        alt_hint = ""
                        for f in ledger.verified_facts:
                            nf = _normalize_for_match(f.quote)
                            if nf and (nq in nf or nf in nq):
                                alt_hint = (
                                    f" Your quote matches ledger locator "
                                    f"{json.dumps(f.locator.model_dump(exclude_none=True))}; pair the matching locator and quote."
                                )
                                break
                        errors.append(
                            f"{label} quote at '{loc.locator_key}' does not match verified ledger text."
                            f"{alt_hint}"
                        )
            elif loc.cell_range:
                matched_cells = facts_by_cell.get((loc.file_name, loc.cell_range))
                if not matched_cells:
                    errors.append(
                        f"{label} cites spreadsheet cell "
                        f"'{loc.file_name}!{loc.cell_range}' which is not in VerifiedFactLedger."
                        f" Valid ledger locators: {'; '.join(available_hints)}"
                    )

        for group in draft.supports:
            for item in group.items:
                # L1 verification when citing factual evidence against a non-empty ledger
                if item.type == "evidence" and ledger.verified_facts:
                    _check_evidence_node(item, f"SupportGroup n={group.n} item")

                # L2+ canonical authority verification
                if item.type == "authority" and auth_map:
                    matched_ids = re.findall(r"\b(AUTH:[A-Za-z0-9._:-]+)\b", f"{item.title} {item.quote or ''} {item.body or ''}")
                    for aid in matched_ids:
                        if aid not in auth_map:
                            errors.append(
                                f"SupportGroup n={group.n} references unknown or unauthorized authority '{aid}'."
                            )
                    if item.quote:
                        nq = _normalize_for_match(item.quote)
                        if nq and not any(
                            nq in _normalize_for_match(a.verbatim_quote)
                            or _normalize_for_match(a.verbatim_quote) in nq
                            for a in auth_map.values()
                        ):
                            errors.append(
                                f"SupportGroup n={group.n} authority quote '{item.quote[:60]}' does not match any assigned canonical authority."
                            )

                for sub in item.sub_supports:
                    if sub.type == "evidence" and ledger.verified_facts:
                        _check_evidence_node(sub, f"SupportGroup n={group.n} sub_support n={sub.n}")
                    if sub.type == "authority":
                        if not auth_map:
                            errors.append(
                                f"SupportGroup n={group.n} sub_support n={sub.n} cites authority '{sub.title}', "
                                "but no canonical authorities were assigned to this section."
                            )
                            continue
                        matched_ids = re.findall(
                            r"\b(AUTH:[A-Za-z0-9._:-]+)\b",
                            f"{sub.title} {sub.quote or ''} {sub.body or ''}",
                        )
                        for aid in matched_ids:
                            if aid not in auth_map:
                                errors.append(
                                    f"SupportGroup n={group.n} sub_support n={sub.n} references unknown authority '{aid}'."
                                )
                        if sub.quote:
                            nq = _normalize_for_match(sub.quote)
                            if nq and not any(
                                nq in _normalize_for_match(a.verbatim_quote)
                                or _normalize_for_match(a.verbatim_quote) in nq
                                for a in auth_map.values()
                            ):
                                errors.append(
                                    f"SupportGroup n={group.n} sub_support n={sub.n} authority quote does not match canonical verbatim text."
                                )

        return errors
